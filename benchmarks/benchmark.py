"""Times the same work on the GPU and on the CPU.

The point of a Metal backend on Apple silicon is not that it can run an op but
that it is worth running there, so the number that matters is the ratio, and
the honest way to get it is to run the identical graph on both devices in the
same process with the same data.

Every measurement waits for the device before stopping the clock, since a
Metal command buffer is asynchronous and an unwaited timing measures how fast
work can be enqueued.

Two things here are about not believing the numbers too easily.

The devices are timed alternately rather than in two phases. Timing every GPU
repetition and then every CPU repetition makes any drift between the phases
look like a result: on a laptop that is thermal throttling and whatever else
is running, and it moved the measured speedup of a training step between 0.9x
and 4.3x across three consecutive runs of an earlier version of this script.
Alternating puts both devices under the same conditions.

That was not enough on its own. With the devices interleaved and 75 paired
repetitions, two consecutive runs still disagreed: ReduceSum came out at 0.57x
and then 1.67x, the training step at 1.46x and then 2.20x. The variance is
between runs, not within them, so the spread of paired ratios inside one run
understates it, and adding repetitions does not help. So the whole suite runs
several times and what is reported is the median across those runs, with the
range they spanned. A case whose range crosses 1.0 has not been shown to be
faster on either device, whatever its median says, and this marks those
rather than letting a median stand alone.
"""

import argparse
import statistics
import time

import numpy as np
import tensorflow as tf
from tensorflow.python.framework import load_library


def sync(tensor):
  """Forces the work to have happened before the clock stops."""
  if isinstance(tensor, (list, tuple)):
    for item in tensor:
      sync(item)
    return
  # Reading one element brings the device to a stop for this stream.
  np.asarray(tensor).reshape(-1)[:1]


def once(fn, device):
  """One timed repetition on one device."""
  with tf.device(device):
    start = time.perf_counter()
    sync(fn())
    return time.perf_counter() - start


def paired(fn, warmup=5, runs=25):
  """Times both devices alternately, returning (gpu, cpu, ratios).

  ratios is per matched pair, so it carries the spread rather than only the
  middle. Both devices are warmed first: the first call on either compiles
  something, and on the GPU it also builds and caches an MPSGraph.
  """
  for device in ("/GPU:0", "/CPU:0"):
    for _ in range(warmup):
      once(fn, device)

  gpu, cpu, ratios = [], [], []
  for index in range(runs):
    # Alternating which device goes first as well, so that neither is
    # systematically the one paying for whatever the other left behind.
    order = ("/GPU:0", "/CPU:0") if index % 2 == 0 else ("/CPU:0", "/GPU:0")
    timings = {device: once(fn, device) for device in order}
    gpu.append(timings["/GPU:0"])
    cpu.append(timings["/CPU:0"])
    ratios.append(timings["/CPU:0"] / timings["/GPU:0"])
  return gpu, cpu, ratios


def measure(fn, runs):
  """One run of one case: median GPU time, median CPU time, median ratio."""
  gpu, cpu, ratios = paired(fn, runs=runs)
  return (statistics.median(gpu) * 1e3, statistics.median(cpu) * 1e3,
          statistics.median(ratios))


def build_model():
  return tf.keras.Sequential([
      tf.keras.layers.Input((32, 32, 3)),
      tf.keras.layers.Conv2D(32, 3, padding="same", activation="relu"),
      tf.keras.layers.MaxPooling2D(),
      tf.keras.layers.Conv2D(64, 3, padding="same", activation="relu"),
      tf.keras.layers.MaxPooling2D(),
      tf.keras.layers.Flatten(),
      tf.keras.layers.Dense(128, activation="relu"),
      tf.keras.layers.Dense(10),
  ])


def write_report(path, rows, runs, repeats):
  """Writes BENCHMARKS.md."""
  import platform  # pylint: disable=g-import-not-at-top
  with open(path, "w") as report:
    report.write("# GPU against CPU\n\n")
    report.write(
        "Generated by `make benchmark`. Do not edit by hand.\n\n"
        f"TensorFlow {tf.__version__}, macOS {platform.mac_ver()[0]}, "
        f"{platform.machine()}. The whole suite was run "
        f"{'once' if repeats == 1 else f'{repeats} times'}, each case {runs} "
        "paired repetitions per run after 5 warmups on each device.\n\n"
        "Both devices run the identical graph on the identical data in one "
        "process, timed alternately rather than in two phases, because "
        "timing all of one device and then all of the other turns drift "
        "between the phases into a result.\n\n"
        "**The range is across runs, and it is wide.** That is the honest "
        "measurement, not a defect in the table: interleaving fixed the "
        "phase problem but the remaining variance is between whole runs "
        "rather than within them, so more repetitions inside a run do not "
        "narrow it. On this machine, a laptop that throttles and shares its "
        "memory bandwidth with everything else running, a case is worth "
        "believing when its range is narrow and sits clear of 1.0.\n\n"
        "**A case marked (spans 1.0) has not been shown to be faster on "
        "either device.** Its runs landed on both sides. The median alone "
        "would hide that.\n\n"
        "Every measurement waits for the device before stopping the clock: a "
        "Metal command buffer is asynchronous, and an unwaited timing "
        "measures how fast work can be enqueued.\n\n")
    report.write("| Case | GPU ms | CPU ms | speedup | across runs |\n")
    report.write("| --- | ---: | ---: | ---: | ---: |\n")
    for name, gpu_ms, cpu_ms, ratio, low, high in sorted(
        rows, key=lambda row: row[3], reverse=True):
      spans = low < 1.0 < high
      bold = not spans and low > 1.5
      shown = f"**{ratio:.2f}x**" if bold else f"{ratio:.2f}x"
      span = f"{low:.2f}..{high:.2f}" + (" (spans 1.0)" if spans else "")
      report.write(f"| {name} | {gpu_ms:.2f} | {cpu_ms:.2f} | {shown} | "
                   f"{span} |\n")
    report.write(
        "\nBold marks a case whose slowest run still beat the CPU by more "
        "than half again, which is the bar for calling it a win on this "
        "hardware.\n")


def main():
  parser = argparse.ArgumentParser()
  parser.add_argument("--plugin", default=None)
  parser.add_argument("--runs", type=int, default=25,
                      help="paired repetitions per case per run")
  parser.add_argument("--repeats", type=int, default=3,
                      help="how many times to run the whole suite; the "
                           "variance that matters is between runs, not "
                           "within one")
  parser.add_argument("--report", default=None,
                      help="write the table to this file, as markdown")
  args = parser.parse_args()
  if args.plugin:
    load_library.load_pluggable_device_library(args.plugin)
  print(f"tensorflow {tf.__version__}")
  devices = [d.name for d in tf.config.list_physical_devices()]
  print(f"devices {devices}")
  if not any("GPU" in d for d in devices):
    print("no GPU device, nothing to compare")
    return 1
  tf.config.set_soft_device_placement(True)

  # Both generators, since the model's initialisers draw from TensorFlow's.
  tf.random.set_seed(0)
  rng = np.random.default_rng(0)
  cases = []

  for n in (512, 1024, 2048):
    a = tf.constant(rng.standard_normal((n, n), dtype=np.float32))
    cases.append((f"MatMul {n}x{n}", lambda a=a: tf.matmul(a, a)))

  for batch in (16, 64):
    image = tf.constant(rng.standard_normal((batch, 64, 64, 32),
                                            dtype=np.float32))
    filt = tf.constant(rng.standard_normal((3, 3, 32, 64), dtype=np.float32))
    cases.append((f"Conv2D batch {batch}",
                  lambda i=image, f=filt: tf.nn.conv2d(i, f, 1, "SAME")))

  big = tf.constant(rng.standard_normal((4096, 4096), dtype=np.float32))
  cases.append(("Elementwise 4096x4096", lambda: tf.nn.relu(big * 2.0 + 1.0)))
  cases.append(("ReduceSum 4096x4096", lambda: tf.reduce_sum(big, axis=1)))

  model = build_model()
  model.build((None, 32, 32, 3))
  for batch in (32, 128):
    x = tf.constant(rng.standard_normal((batch, 32, 32, 3), dtype=np.float32))
    cases.append((f"CNN forward batch {batch}",
                  lambda x=x, m=model: m(x, training=False)))

  # A training step with plain SGD, which needs no fused optimiser.
  y = tf.constant(rng.integers(0, 10, 128).astype(np.int32))
  x = tf.constant(rng.standard_normal((128, 32, 32, 3), dtype=np.float32))
  loss_fn = tf.keras.losses.SparseCategoricalCrossentropy(from_logits=True)
  optimiser = tf.keras.optimizers.SGD(0.01)

  def train_step():
    with tf.GradientTape() as tape:
      loss = loss_fn(y, model(x, training=True))
    grads = tape.gradient(loss, model.trainable_variables)
    optimiser.apply_gradients(zip(grads, model.trainable_variables))
    return loss

  cases.append(("CNN train step, SGD, batch 128", train_step))

  # The suite runs end to end several times rather than each case several
  # times in a row, so that a case is not measured entirely inside one thermal
  # state. The reported figure is the median of those runs.
  per_case = {name: [] for name, _ in cases}
  failed = {}
  for repeat in range(args.repeats):
    print(f"\nrun {repeat + 1} of {args.repeats}")
    for name, fn in cases:
      if name in failed:
        continue
      try:
        per_case[name].append(measure(fn, args.runs))
      except (tf.errors.OpError, ValueError, TypeError) as error:
        # An op with no kernel raises OpError; a case whose inputs do not suit
        # the op raises from Python before it gets that far. Anything else is
        # not this script's to swallow.
        failed[name] = str(error).splitlines()[0][:60]

  rows = []
  print(f"\n{'case':34s} {'GPU ms':>9s} {'CPU ms':>9s} {'speedup':>9s} "
        f"{'across runs':>16s}")
  print("-" * 84)
  for name, _ in cases:
    if name in failed:
      print(f"{name:34s} {failed[name]}")
      continue
    samples = per_case[name]
    gpu_ms = statistics.median(row[0] for row in samples)
    cpu_ms = statistics.median(row[1] for row in samples)
    ratios = [row[2] for row in samples]
    ratio = statistics.median(ratios)
    low, high = min(ratios), max(ratios)
    # A case whose runs land on both sides of 1.0 has not been shown to favour
    # either device, whatever the median says.
    mark = " ?" if low < 1.0 < high else "  "
    print(f"{name:34s} {gpu_ms:9.2f} {cpu_ms:9.2f} {ratio:8.2f}x{mark}"
          f"{low:6.2f}..{high:<6.2f}")
    rows.append((name, gpu_ms, cpu_ms, ratio, low, high))

  if args.repeats > 1:
    print("\n? marks a case whose runs landed on both sides of 1.0: on this "
          "machine\n  it has not been shown to be faster on either device.")
  else:
    print("\nOne run, so there is no across-run range and nothing here "
          "should be\n  trusted to better than a factor of two. Use "
          "--repeats.")

  if args.report:
    write_report(args.report, rows, args.runs, args.repeats)
    print(f"\nwrote {args.report}")
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
